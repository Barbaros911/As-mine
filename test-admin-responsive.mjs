const build=fs.readFileSync('construire.sh','utf8');
const html=fs.readFileSync('admin-v2.html','utf8');
const ok=(v,m)=>{if(!v)throw new Error(m)};
ok(css.includes('env(safe-area-inset-bottom'), 'safe-area iPhone absente');
ok(css.includes('@media(max-width:800px)'), 'breakpoint mobile absent');
ok(css.includes('min-height:var(--tap)'), 'cibles tactiles absentes');
ok(css.includes('overflow-x:hidden'), 'protection débordement horizontal absente');
ok(css.includes('.mobile-bottom-nav'), 'navigation de travail mobile absente');
ok(css.includes('.dash-required'), 'zone réservations à traiter non adaptée au mobile');
ok(css.includes('.sheet>div'), 'fiche réservation mobile non adaptée');
ok(js.includes("data-mgo=\"bookings\""), 'accès Réservations mobile absent');
ok(js.includes('mobile-create'), 'création de réservation mobile absente');
ok(js.includes("data-filter=\"today\""), 'accès Trajets mobile absent');
ok(js.includes("typeof state!=='undefined'&&Array.isArray(state.courses)"), 'les trajets dérivés ne lisent pas le vrai state Admin');
ok(js.includes("filter==='today'"), 'le bouton Trajets ne filtre pas réellement les réservations du jour');
